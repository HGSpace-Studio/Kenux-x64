void draw_char(screen_t *screen, uint32_t x, uint32_t y, char c, uint8_t r, uint8_t g, uint8_t b) {
    if (c < 32 || c > 127) c = ' ';
    const uint8_t *glyph = font_data[c - 32];
    
    for (uint32_t row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (uint32_t col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                draw_pixel(screen, x + col, y + row, r, g, b);
            }
        }
    }
}

void draw_string(screen_t *screen, uint32_t x, uint32_t y, const char *str, uint8_t r, uint8_t g, uint8_t b) {
    while (*str) {
        draw_char(screen, x, y, *str, r, g, b);
        x += 8;
        str++;
    }
}

efi_status_t init_graphics(efi_system_table_t *st, screen_t *screen) {
    efi_guid_t gop_guid = GRAPHICS_OUTPUT_PROTOCOL_GUID;
    efi_graphics_output_t *gop = NULL;
    efi_boot_services_t *bs = get_boot_services(st);
    efi_locate_protocol_t locate_protocol = (efi_locate_protocol_t)bs->locate_protocol;
    efi_status_t status = locate_protocol(&gop_guid, NULL, (void **)&gop);
    if (status == EFI_SUCCESS && gop && gop->mode && gop->mode->info) {
        screen->gop = gop;
        screen->width = gop->mode->info->horizontal_resolution;
        screen->height = gop->mode->info->vertical_resolution;
        screen->frame_buffer = gop->mode->frame_buffer_base;
        screen->buffer_size = gop->mode->frame_buffer_size;
        screen->pixels_per_scanline = gop->mode->info->pixels_per_scanline;
        screen->pixel_format = gop->mode->info->pixel_format;
        return EFI_SUCCESS;
    }

    screen->gop = NULL;
    screen->width = 80;
    screen->height = 25;
    screen->frame_buffer = 0xB8000;
    screen->buffer_size = 80 * 25 * 2;
    screen->pixels_per_scanline = 80;
    screen->pixel_format = 0;
    return EFI_NOT_FOUND;
}
