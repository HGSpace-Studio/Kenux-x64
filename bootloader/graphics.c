void draw_pixel(screen_t *screen, uint32_t x, uint32_t y, uint8_t r, uint8_t g, uint8_t b) {
    if (x >= screen->width || y >= screen->height) return;
    
    uint64_t offset = (uint64_t)y * screen->pixels_per_scanline * 4 + (uint64_t)x * 4;
    volatile uint32_t *fb = (volatile uint32_t*)(screen->frame_buffer + offset);
    
    if (screen->pixel_format == 0) {
        *fb = (r << 16) | (g << 8) | b | 0xFF000000;
    } else {
        *fb = (b << 16) | (g << 8) | r | 0xFF000000;
    }
}

void draw_rect(screen_t *screen, uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint8_t r, uint8_t g, uint8_t b) {
    for (uint32_t dy = 0; dy < h; dy++) {
        for (uint32_t dx = 0; dx < w; dx++) {
            draw_pixel(screen, x + dx, y + dy, r, g, b);
        }
    }
}

void draw_circle(screen_t *screen, uint32_t cx, uint32_t cy, uint32_t radius, uint8_t r, uint8_t g, uint8_t b) {
    int32_t x = radius;
    int32_t y = 0;
    int32_t err = 0;
    
    while (x >= y) {
        draw_pixel(screen, cx + x, cy + y, r, g, b);
        draw_pixel(screen, cx + y, cy + x, r, g, b);
        draw_pixel(screen, cx - y, cy + x, r, g, b);
        draw_pixel(screen, cx - x, cy + y, r, g, b);
        draw_pixel(screen, cx - x, cy - y, r, g, b);
        draw_pixel(screen, cx - y, cy - x, r, g, b);
        draw_pixel(screen, cx + y, cy - x, r, g, b);
        draw_pixel(screen, cx + x, cy - y, r, g, b);
        
        if (err <= 0) {
            y += 1;
            err += 2*y + 1;
        }
        if (err > 0) {
            x -= 1;
            err -= 2*x + 1;
        }
    }
}

void draw_filled_circle(screen_t *screen, uint32_t cx, uint32_t cy, uint32_t radius, uint8_t r, uint8_t g, uint8_t b) {
    for (int32_t y = -(int32_t)radius; y <= (int32_t)radius; y++) {
        for (int32_t x = -(int32_t)radius; x <= (int32_t)radius; x++) {
            if (x*x + y*y <= radius*radius) {
                draw_pixel(screen, cx + x, cy + y, r, g, b);
            }
        }
    }
}

