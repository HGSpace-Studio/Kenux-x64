#define S_REGISTRY_COUNT (sizeof(s_registry) / sizeof(s_registry[0]))

const icon_registry_entry_t* icon_registry_get(size_t* count) {
    if (count) *count = S_REGISTRY_COUNT;
    return s_registry;
}

icon_id_t icon_registry_lookup(const char* name) {
    if (!name) return ICON_NONE;
    for (size_t i = 0; i < S_REGISTRY_COUNT; i++) {
        if (strcmp(s_registry[i].name, name) == 0)
            return s_registry[i].id;
    }
    return ICON_NONE;
}

const char* icon_registry_get_name(icon_id_t id) {
    for (size_t i = 0; i < S_REGISTRY_COUNT; i++) {
        if (s_registry[i].id == id)
            return s_registry[i].name;
    }
    return NULL;
}

const char* icon_registry_get_category(icon_id_t id) {
    for (size_t i = 0; i < S_REGISTRY_COUNT; i++) {
        if (s_registry[i].id == id)
            return s_registry[i].category;
    }
    return NULL;
}

size_t icon_registry_count_by_category(const char* category) {
    if (!category) return 0;
    size_t cnt = 0;
    for (size_t i = 0; i < S_REGISTRY_COUNT; i++) {
        if (strcmp(s_registry[i].category, category) == 0)
            cnt++;
    }
    return cnt;
}
