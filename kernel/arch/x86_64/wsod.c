static void wsod_draw_text(int x, int y, const char* text, uint32_t fg, uint32_t bg)
{
    int cx = x;
    while (*text) {
        if (*text == '\n') {
            cx = x;
            y += 18;
            text++;
            continue;
        }
        wsod_draw_char(cx, y, *text, fg, bg);
        cx += 9;
        text++;
    }
}

static void wsod_draw_progress_bar(int x, int y, int w, int h, int pct, uint32_t fill, uint32_t bg)
{
    wsod_fill_rect(x, y, w, h, bg);
    int fill_w = (w * pct) / 100;
    wsod_fill_rect(x, y, fill_w, h, fill);
}

void wsod_init(uint32_t* fb, int width, int height)
{
    wsod.fb = fb;
    wsod.width = width;
    wsod.height = height;
    wsod.stride = width;
    wsod.crash_time = 0;
    wsod.error_code = 0;
    wsod.message[0] = '\0';
    wsod.module[0] = '\0';
    wsod.stack_trace[0] = '\0';
    wsod.trace_count = 0;
}

void wsod_show(int error_code, const char* message, const char* module)
{
    if (!wsod.fb) return;

    wsod_fill_rect(0, 0, wsod.width, wsod.height, WSOD_BG_COLOR);

    int cx = wsod.width / 2;
    int cy = wsod.height / 4;

    wsod_draw_text(cx - 180, cy, "KENUX", WSOD_ACCENT, WSOD_BG_COLOR);

    cy += 40;
    wsod_draw_text(cx - 250, cy, "A problem has been detected and the system has been shut down",
                   WSOD_FG_COLOR, WSOD_BG_COLOR);

    cy += 40;
    if (message) {
        wsod_draw_text(cx - 250, cy, message, WSOD_WARN_COLOR, WSOD_BG_COLOR);
    }

    cy += 30;
    if (module) {
        char mod_msg[128];
        int len = 0;
        const char* prefix = "Error in module: ";
        while (prefix[len]) { mod_msg[len] = prefix[len]; len++; }
        int ml = 0;
        while (module[ml] && len < 126) { mod_msg[len++] = module[ml++]; }
        mod_msg[len] = '\0';
        wsod_draw_text(cx - 250, cy, mod_msg, WSOD_FG_COLOR, WSOD_BG_COLOR);
    }

    cy += 40;
    char code_msg[64];
    const char* p = "Error code: 0x";
    int ci = 0;
    while (p[ci]) { code_msg[ci] = p[ci]; ci++; }
    const char hex[] = "0123456789ABCDEF";
    code_msg[ci++] = hex[(error_code >> 28) & 0xF];
    code_msg[ci++] = hex[(error_code >> 24) & 0xF];
    code_msg[ci++] = hex[(error_code >> 20) & 0xF];
    code_msg[ci++] = hex[(error_code >> 16) & 0xF];
    code_msg[ci++] = hex[(error_code >> 12) & 0xF];
    code_msg[ci++] = hex[(error_code >> 8) & 0xF];
    code_msg[ci++] = hex[(error_code >> 4) & 0xF];
    code_msg[ci++] = hex[error_code & 0xF];
    code_msg[ci] = '\0';
    wsod_draw_text(cx - 250, cy, code_msg, WSOD_FG_COLOR, WSOD_BG_COLOR);

    cy += 50;
    wsod_draw_text(cx - 250, cy, "Collecting error data...", WSOD_FG_COLOR, WSOD_BG_COLOR);
    cy += 25;
    wsod_draw_progress_bar(cx - 250, cy, 500, 8, 30, WSOD_ACCENT, 0x003366);

    cy += 40;
    wsod_draw_text(cx - 250, cy, "System will restart after data collection completes.",
                   WSOD_FG_COLOR, WSOD_BG_COLOR);
}

void wsod_add_stack_frame(uint64_t addr, const char* symbol)
{
    if (wsod.trace_count >= 16) return;

    char line[64];
    int pos = 0;
    line[pos++] = '#';
    if (wsod.trace_count < 10) line[pos++] = '0' + wsod.trace_count;
    else { line[pos++] = '1'; line[pos++] = '0'; }
    line[pos++] = ' ';

    const char* prefix = "0x";
    line[pos++] = prefix[0]; line[pos++] = prefix[1];
    const char hex[] = "0123456789ABCDEF";
    for (int i = 60; i >= 0; i -= 4) {
        line[pos++] = hex[(addr >> i) & 0xF];
        if (pos >= 50) break;
    }

    if (symbol) {
        line[pos++] = ' ';
        line[pos++] = '(';
        int si = 0;
        while (symbol[si] && pos < 60) line[pos++] = symbol[si++];
        line[pos++] = ')';
    }
    line[pos] = '\0';

    int offset = wsod.trace_count * 40;
    if (offset + pos + 1 < 512) {
        memcpy(wsod.stack_trace + offset, line, pos + 1);
    }
    wsod.trace_count++;
}

