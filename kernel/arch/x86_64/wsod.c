#define WSOD_BG_COLOR    0x001B3A
#define WSOD_FG_COLOR    0xFFFFFF
#define WSOD_ACCENT      0xFF4444
#define WSOD_WARN_COLOR  0xFFAA00

typedef struct {
    uint32_t* fb;
    int width;
    int height;
    int stride;
    uint64_t crash_time;
    int error_code;
    char message[256];
    char module[64];
    char stack_trace[512];
    int trace_count;
} wsod_state_t;

static wsod_state_t wsod;

static void wsod_fill_rect(int x, int y, int w, int h, uint32_t color)
{
    for (int dy = 0; dy < h; dy++) {
        for (int dx = 0; dx < w; dx++) {
            int px = x + dx;
            int py = y + dy;
            if (px >= 0 && px < wsod.width && py >= 0 && py < wsod.height) {
                wsod.fb[py * wsod.width + px] = color;
            }
        }
    }
}

